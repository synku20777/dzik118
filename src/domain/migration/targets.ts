// The fields a spreadsheet column can be mapped to, per kind of import, with
// header aliases in English, Latvian and Russian (ADR 0013). Aliases are plain
// words; matching folds case and diacritics (values.ts foldText), so "Dzīvokļa
// Nr." and "dzivokla nr" are the same alias.
import type { PatternClass } from "./shapes";
import { foldText } from "./values";

export type MigrationKind = "DWELLINGS" | "BALANCES" | "METERS";

export interface TargetField {
  key: string;
  // English label, shown through t() on the mapping page.
  label: string;
  required: boolean;
  // Column shapes that can hold this field. A column of another shape is not
  // proposed for it.
  expects: PatternClass[];
  aliases: string[];
  // One written-out sentence, for the optional AI step ("write the criteria").
  description: string;
}

