// Aliases folded once, the same way headers are folded.
const foldedAliases = new Map<string, string[]>();
export function aliasesOf(field: TargetField): string[] {
  let folded = foldedAliases.get(field.key);
  if (!folded) {
    folded = field.aliases.map(foldText);
    foldedAliases.set(field.key, folded);
  }
  return folded;
}

