// Phase L (Automation/audit) - runs automatically after `astro build` (see
// package.json's "postbuild" script). Astro's Cloudflare adapter only ever
// builds a `fetch` handler; Cloudflare Cron Triggers need a `scheduled`
// export on the same Worker, which the adapter has no config hook for. This
// writes a tiny wrapper next to the adapter's own generated entry.mjs (a
// stable filename the adapter always uses, unlike its hashed chunk names,
// which is why the wrapper self-fetches an API route -- see
// src/pages/api/v1/internal/scheduled-jobs.ts -- instead of importing
// scheduler code directly) and repoints the adapter's generated
// dist/server/wrangler.json at it. Every other field in that generated
// config (bindings, triggers, etc., all sourced from the project's own
// wrangler.jsonc) is preserved untouched.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const projectRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const serverDir = path.join(projectRoot, "dist", "server");
const wranglerConfigPath = path.join(serverDir, "wrangler.json");
const wrapperPath = path.join(serverDir, "scheduled-entry.mjs");

const wrapperSource = `// Generated by scripts/postbuild-wire-scheduled.mjs -- do not edit by hand,
// this file is overwritten on every build.
import astroWorker from "./entry.mjs";

const INTERNAL_ORIGIN = "https://internal";

export default {
  fetch: astroWorker.fetch,
  async scheduled(event, env, ctx) {
    // Astro's built-in CSRF origin-check middleware (node_modules/astro/
    // dist/core/app/origin-check.js) rejects any non-GET request whose
    // Origin header doesn't exactly match the request URL's own origin --
    // it applies to every route, not just Actions/forms. A same-origin
    // Origin header here satisfies that check for this internal call.
    const request = new Request(INTERNAL_ORIGIN + "/api/v1/internal/scheduled-jobs", {
      method: "POST",
      headers: {
        "x-internal-cron-secret": env.INTERNAL_CRON_SECRET ?? "",
        "origin": INTERNAL_ORIGIN,
      },
    });
    // Awaiting and checking the response (rather than fire-and-forget) is
    // what makes a failure observable at the Cloudflare Cron Trigger level
    // (spec Section 32: "observable") -- a promise passed to ctx.waitUntil
    // that rejects marks that invocation failed in Cloudflare's own Cron
    // Trigger execution log; one that just resolves never does, even if
    // the endpoint returned 403/500.
    ctx.waitUntil(
      astroWorker.fetch(request, env, ctx).then((response) => {
        if (!response.ok) {
          throw new Error("scheduled-jobs endpoint failed: " + response.status);
        }
      })
    );
  },
};
`;

writeFileSync(wrapperPath, wrapperSource);

const config = JSON.parse(readFileSync(wranglerConfigPath, "utf-8"));
config.main = "scheduled-entry.mjs";
writeFileSync(wranglerConfigPath, JSON.stringify(config, null, 2));

console.log(
  "postbuild-wire-scheduled: wired scheduled-entry.mjs as the Worker's main entry point"
);
